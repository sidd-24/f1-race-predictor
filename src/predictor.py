def predict_from_historical(
    year: int,
    round_number: int,
    data_prefix: str = DEFAULT_DATA_PREFIX,
    model_name: str = "best_model"
) -> pd.DataFrame:
    """
    Make predictions using historical data (for testing).
    Uses already collected qualifying data.
    """
    model = load_model(model_name)

    # Load features file
    features_path = resolve_data_file(data_prefix, "features")
    if not features_path.exists():
        raise FileNotFoundError(
            f"Features file not found: {features_path.name}. Run feature engineering first."
        )

    all_features = pd.read_csv(features_path)

    # Filter for specific race
    race_features = all_features[
        (all_features['Year'] == year) &
        (all_features['Round'] == round_number)
    ].copy()

    if race_features.empty:
        raise ValueError(f"No data found for {year} Round {round_number}")

    # Make predictions
    feature_cols = get_feature_columns()
    X = race_features[feature_cols]
    predictions = predict_positions(model, X)

    # Create results
    results = race_features[['Driver', 'Team', 'GridPosition']].copy()
    results['PredictedPosition'] = predictions
    results['ActualPosition'] = race_features['FinishingPosition']
    results = results.sort_values('PredictedPosition').reset_index(drop=True)
    results['PredictedRank'] = range(1, len(results) + 1)

    return results


def was_training_race(year: int, round_number: int, data_prefix: str = DEFAULT_DATA_PREFIX) -> bool:
    """
    True if the race falls in the training part of the chronological split
    used by src.model (everything before the newest TEST_SIZE share of rows).
    """
    features_path = resolve_data_file(data_prefix, "features")
    if not features_path.exists():
        return False
    races = pd.read_csv(features_path, usecols=['Year', 'Round']).sort_values(['Year', 'Round'])
    first_test = races.iloc[len(races) - max(1, int(len(races) * TEST_SIZE))]
    return (year, round_number) < (int(first_test['Year']), int(first_test['Round']))


def compare_predictions(results: pd.DataFrame, event_name: str = "Race"):
    """Compare predictions vs actual results."""
    print("\n" + "=" * 80)
    print(f"[F1] PREDICTION vs ACTUAL: {event_name}")
    print("=" * 80)
    print(f"{'Driver':<10}{'Predicted':<12}{'Actual':<10}{'Diff':<10}{'Result'}")
    print("-" * 80)

    correct = 0
    within_3 = 0

    for idx, row in results.iterrows():
        driver = row['Driver']
        pred = int(row['PredictedPosition'])
        actual = int(row['ActualPosition'])
        diff = pred - actual

        if diff == 0:
            result = "[OK] EXACT"
            correct += 1
            within_3 += 1
        elif abs(diff) <= 3:
            result = "[~] Close"
            within_3 += 1
        else:
            result = "[X] Miss"

        diff_str = f"+{diff}" if diff > 0 else str(diff)
        print(f"{driver:<10}P{pred:<11}P{actual:<9}{diff_str:<10}{result}")

    print("-" * 80)
    print(f"Exact predictions: {correct}/{len(results)} ({100*correct/len(results):.1f}%)")
    print(f"Within 3 positions: {within_3}/{len(results)} ({100*within_3/len(results):.1f}%)")
    print("=" * 80)


def get_next_race_info(
    year: int = None,
    data_prefix: str = DEFAULT_DATA_PREFIX
):
    """
    Get information about the next upcoming race.

    Returns:
        tuple: (year, round_number, event_name, event_date, qualifying_available)
    """
    from .data_collector import get_event_schedule

    if year is None:
        year = pd.Timestamp.now().year

    schedule = get_event_schedule(year)
    if schedule.empty:
        return None

    # Find next race (event date >= today)
    now = pd.Timestamp.now()
    upcoming = schedule[schedule['EventDate'] >= now.normalize()]

    if upcoming.empty:
        # Try next year
        year += 1
        schedule = get_event_schedule(year)
        upcoming = schedule[schedule['EventDate'] >= now.normalize()]
        if upcoming.empty:
            return None

    next_race = upcoming.iloc[0]
    round_number = int(next_race['RoundNumber'])
    event_name = next_race['EventName']
    event_date = next_race['EventDate']

    qualifying_path = resolve_data_file(data_prefix, "qualifying")
    qualifying_available = False
    if qualifying_path.exists():
        qualifying = pd.read_csv(qualifying_path, usecols=['Year', 'Round'])
        qualifying_available = (
            ((pd.to_numeric(qualifying['Year'], errors='coerce') == year) &
             (pd.to_numeric(qualifying['Round'], errors='coerce') == round_number))
            .any()
        )

    # The local dataset is authoritative; the date is only a fallback hint.
    quali_date = event_date - pd.Timedelta(days=1)
    qualifying_date_reached = now >= quali_date

    return {
        'year': year,
        'round': round_number,
        'event_name': event_name,
        'event_date': event_date,
        'qualifying_available': qualifying_available,
        'qualifying_date_reached': qualifying_date_reached
    }


def resolve_race_query(race_query: str, default_year: int) -> dict:
    """
    Resolve a race query string to season year, round number, and event name.

    Supported query formats:
    - "Abu Dhabi Grand Prix"
    - "Abu Dhabi Grand Prix 2024"
    """
    from .data_collector import get_event_schedule

    query = race_query.strip()
    year = default_year

    year_match = re.search(r'(\d{4})\s*$', query)
    if year_match:
        year = int(year_match.group(1))
        query = query[:year_match.start()].strip()

    if not query:
        raise ValueError("Race name cannot be empty.")

    schedule = get_event_schedule(year)
    if schedule.empty:
        raise ValueError(f"Could not load race schedule for {year}.")

    event_names = schedule['EventName'].fillna("").astype(str)
    exact_match = schedule[event_names.str.casefold() == query.casefold()]
    if not exact_match.empty:
        race = exact_match.iloc[0]
        return {
            'year': year,
            'round': int(race['RoundNumber']),
            'event_name': race['EventName']
        }

    partial_match = schedule[event_names.str.contains(query, case=False, regex=False)]
    if len(partial_match) == 1:
        race = partial_match.iloc[0]
        return {
            'year': year,
            'round': int(race['RoundNumber']),
            'event_name': race['EventName']
        }

    if len(partial_match) > 1:
        matches = ", ".join(partial_match['EventName'].astype(str).tolist())
        raise ValueError(f"Race name is ambiguous. Matches: {matches}")

    raise ValueError(f"No race named '{query}' found in {year} schedule.")


def build_prediction_from_standings(
    year: int,
    model_name: str = "best_model",
    data_prefix: str = DEFAULT_DATA_PREFIX
) -> pd.DataFrame:
    """Build prediction dataframe using championship standings as an estimated grid."""
    model = load_model(model_name)

    standings = get_current_standings(year, data_prefix)
    if standings.empty:
        standings = get_current_standings(year - 1, data_prefix)

    if standings.empty:
        return pd.DataFrame()

    standings = standings.sort_values('DriverChampionshipPosition')
    standings_year = int(standings['Year'].iloc[0])

    # Season standings can include replacement drivers who no longer have a
    # seat. Use the latest completed race to identify the current race roster.
    races_path = resolve_data_file(data_prefix, "races")
    if races_path.exists():
        races = pd.read_csv(races_path)
        races['Year'] = pd.to_numeric(races['Year'], errors='coerce')
        races['Round'] = pd.to_numeric(races['Round'], errors='coerce')
        latest_round = standings['Round'].max()
        available_rounds = races.loc[
            (races['Year'] == standings_year) &
            (races['Round'] <= latest_round),
            'Round'
        ].dropna()
        if not available_rounds.empty:
            latest_round = available_rounds.max()
        latest_race = races[
            (races['Year'] == standings_year) &
            (races['Round'] == latest_round)
        ]
        active_drivers = latest_race['Abbreviation'].dropna().astype(str).unique()
        if len(active_drivers) > 0:
            standings = standings[standings['Driver'].isin(active_drivers)]

    # F1's current maximum grid size is 22 cars.
    if len(standings) > 22:
        logger.warning(
            "Limiting standings-based prediction from %d to 22 drivers.",
            len(standings)
        )
        standings = standings.head(22)

    features = []
    for grid_pos, (_, row) in enumerate(standings.iterrows(), 1):
        features.append({
            'Driver': row['Driver'],
            'FullName': row['Driver'],
            'Team': row['TeamName'],
            'GridPosition': grid_pos,
            'DriverChampPosition': row['DriverChampionshipPosition'],
            'DriverPoints': row['DriverPointsBefore'],
            'ConstructorChampPosition': row['ConstructorChampionshipPosition'],
            'ConstructorPoints': row['ConstructorPointsBefore'],
            'TrackHistoryAvgPos': grid_pos,
            'RecentForm': grid_pos,
            'QualifyingGap': QUALIFYING_GAP_FILL
        })

    features_df = pd.DataFrame(features)
    feature_cols = get_feature_columns()
    X = features_df[feature_cols]
    predictions = predict_positions(model, X)

    results = features_df[['Driver', 'FullName', 'Team', 'GridPosition']].copy()
    results['PredictedPosition'] = predictions
    results = results.sort_values('PredictedPosition').reset_index(drop=True)
    results['PredictedRank'] = range(1, len(results) + 1)
    return results


def predict_next_race(
    model_name: str = "best_model",
    data_prefix: str = DEFAULT_DATA_PREFIX,
    year: int = None,
    mode: str = "auto"
):
    """
    Predict the next upcoming F1 race.
    """
    print("\n" + "=" * 70)
    print("[F1] FINDING NEXT RACE...")
    print("=" * 70)

    race_info = get_next_race_info(year, data_prefix)

    if race_info is None:
        print("Could not find upcoming race information.")
        return None

    print(f"Next Race: {race_info['event_name']}")
    print(f"Date: {race_info['event_date'].strftime('%Y-%m-%d')}")
    print(f"Round: {race_info['round']}")
    print(f"Qualifying Data Available: {'Yes' if race_info['qualifying_available'] else 'No'}")
    print("-" * 70)

    results = None
    if mode == "standings":
        print("\nUsing standings-based mode (pre-qualifying strategy).")
        print("-" * 70)
        results = build_prediction_from_standings(
            race_info['year'],
            model_name,
            data_prefix
        )
        if not results.empty:
            display_predictions(results, f"{race_info['event_name']} (Pre-Qualifying)")
            return results
        print("Could not generate standings-based prediction.")
        return None

    if mode == "qualifying":
        if not race_info['qualifying_available']:
            print("\nQualifying has not happened yet for this race.")
            print("Run with '--next-mode standings' to predict using pre-qualifying data.")
            return None
        print("\nUsing qualifying-based mode (post-qualifying strategy).")
        print("-" * 70)
        results = predict_race(
            race_info['year'],
            race_info['round'],
            model_name,
            data_prefix
        )
    else:
        if race_info['qualifying_available']:
            print("\nQualifying appears available. Using qualifying-based prediction.")
            print("-" * 70)
            results = predict_race(
                race_info['year'],
                race_info['round'],
                model_name,
                data_prefix
            )
            if results.empty:
                print("\nQualifying data could not be loaded.")
                print("Falling back to standings-based pre-qualifying prediction.")
                results = build_prediction_from_standings(
                    race_info['year'],
                    model_name,
                    data_prefix
                )
        else:
            print("\nQualifying hasn't happened yet.")
            print("Using standings-based pre-qualifying prediction.")
            print("-" * 70)
            results = build_prediction_from_standings(
                race_info['year'],
                model_name,
                data_prefix
            )
            if not results.empty:
                display_predictions(results, f"{race_info['event_name']} (Pre-Qualifying)")
                return results

    if not results.empty:
        display_predictions(results, f"{race_info['event_name']} (Post-Qualifying)")
        return results
    else:
        print("Could not generate predictions with the selected mode.")
        return None


def predict_with_custom_grid(grid_order: list, year: int, model_name: str = "best_model"):
    """
    Make predictions with a custom starting grid.
    Useful for predicting before qualifying or with hypothetical scenarios.

    Args:
        grid_order: List of driver abbreviations in grid order (P1 first)
        year: Season year for standings data
        model_name: Model to use
    """
    model = load_model(model_name)
    standings = get_current_standings(year)

    if standings.empty:
        # Use previous year's final standings
        standings = get_current_standings(year - 1)

    features = []
    for grid_pos, driver in enumerate(grid_order, 1):
        driver_standing = standings[standings['Driver'] == driver]

        if len(driver_standing) > 0:
            driver_champ_pos = driver_standing['DriverChampionshipPosition'].values[0]
            driver_points = driver_standing['DriverPointsBefore'].values[0]
            team = driver_standing['TeamName'].values[0]
            constructor_champ_pos = driver_standing['ConstructorChampionshipPosition'].values[0]
            constructor_points = driver_standing['ConstructorPointsBefore'].values[0]
        else:
            driver_champ_pos = 20
            driver_points = 0
            team = "Unknown"
            constructor_champ_pos = 10
            constructor_points = 0

        features.append({
            'Driver': driver,
            'FullName': driver,
            'Team': team,
            'GridPosition': grid_pos,
            'DriverChampPosition': driver_champ_pos,
            'DriverPoints': driver_points,
            'ConstructorChampPosition': constructor_champ_pos,
            'ConstructorPoints': constructor_points,
            'TrackHistoryAvgPos': grid_pos,
            'RecentForm': grid_pos,
            'QualifyingGap': QUALIFYING_GAP_FILL
        })

    features_df = pd.DataFrame(features)
    feature_cols = get_feature_columns()
    X = features_df[feature_cols]

    predictions = predict_positions(model, X)

    results = features_df[['Driver', 'FullName', 'Team', 'GridPosition']].copy()
    results['PredictedPosition'] = predictions
    results = results.sort_values('PredictedPosition').reset_index(drop=True)
    results['PredictedRank'] = range(1, len(results) + 1)

    return results


def predict_from_standings(
    year: int = None,
    model_name: str = "best_model",
    data_prefix: str = DEFAULT_DATA_PREFIX
):
    """
    Predict race using championship standings as estimated grid order.
    Use this when qualifying data is not available yet.
    """
    print("\n" + "=" * 70)
    print("[F1] PREDICTION FROM CHAMPIONSHIP STANDINGS")
    print("=" * 70)
    print("Note: Using championship order as estimated grid")
    print("      (Qualifying data not available)")
    print("-" * 70)

    if year is None:
        year = pd.Timestamp.now().year

    results = build_prediction_from_standings(year, model_name, data_prefix)
    if results.empty:
        print("Could not load standings data.")
        return None

    display_predictions(results, f"{year} Championship-Based Prediction")

    return results


def main():
    parser = argparse.ArgumentParser(description='F1 Race Position Predictor')
    parser.add_argument('--year', type=str, default='auto', help="Season year or 'auto' for current year")
    parser.add_argument('--round', type=int, help='Race round number')
    parser.add_argument('--race', type=str, help='Race name (e.g. "Monaco Grand Prix" or "Monaco Grand Prix 2024")')
    parser.add_argument('--model', type=str, default='best_model', help='Model to use')
    parser.add_argument('--data-prefix', type=str, default=DEFAULT_DATA_PREFIX, help='Data filename prefix')
    parser.add_argument('--current-standings', action='store_true', help='Show current standings as of today')
    parser.add_argument('--compare', action='store_true', help='Compare with actual results')
    parser.add_argument('--next', action='store_true', dest='next_race', help='Predict next upcoming race')
    parser.add_argument(
        '--next-mode',
        choices=['auto', 'standings', 'qualifying'],
        default='auto',
        help='Next-race strategy: auto detect, standings (pre-qualifying), or qualifying (post-qualifying)'
    )
    parser.add_argument('--standings', action='store_true', help='Predict using championship standings as grid')
    parser.add_argument('--grid', type=str, help='Custom grid order (comma-separated driver codes)')
    parser.add_argument('--debug', action='store_true', help='Show detailed FastF1 request logs')

    args = parser.parse_args()
    configure_fastf1_logging(args.debug)
    effective_year = resolve_cli_year(args.year, parser)

    if args.grid:
        # Custom grid prediction
        grid_order = [d.strip().upper() for d in args.grid.split(',')]
        results = predict_with_custom_grid(grid_order, effective_year, args.model)
        display_predictions(results, f"Custom Grid Prediction")
    elif args.current_standings:
        display_current_standings(effective_year, args.data_prefix)
    elif args.race:
        # A race already in the collected data is compared with its real result;
        # an upcoming race is predicted from its qualifying grid. (Previously a
        # second, unreachable --race branch meant upcoming races failed.)
        try:
            race_info = resolve_race_query(args.race, effective_year)
        except ValueError as exc:
            parser.error(str(exc))
            return

        try:
            results = predict_from_historical(race_info['year'], race_info['round'], args.data_prefix, args.model)
        except (ValueError, FileNotFoundError):
            results = None

        if results is not None:
            print("\n" + "=" * 80)
            print(f"[F1] HISTORICAL ANALYSIS: {race_info['event_name']}")
            print("Comparing model predictions against the actual race results.")
            if was_training_race(race_info['year'], race_info['round'], args.data_prefix):
                print("Note: this race was part of the training data, so the comparison is optimistic.")
            print("=" * 80)
            compare_predictions(results, race_info['event_name'])
        else:
            results = predict_race(race_info['year'], race_info['round'], args.model, args.data_prefix)
            if not results.empty:
                display_predictions(results, race_info['event_name'])
    elif args.standings:
        # Predict from championship standings
        predict_from_standings(effective_year, args.model, args.data_prefix)
    elif args.next_race:
        # Predict next upcoming race
        predict_next_race(args.model, args.data_prefix, effective_year, args.next_mode)
    elif args.compare and args.round:
        # Use historical data for comparison
        results = predict_from_historical(effective_year, args.round, args.data_prefix, args.model)
        compare_predictions(results, f"{effective_year} Round {args.round}")
    elif args.round:
        # Predict specific race
        results = predict_race(effective_year, args.round, args.model, args.data_prefix)
        if not results.empty:
            display_predictions(results, f"{effective_year} Round {args.round}")
    else:
        # Default: predict the next upcoming race
        predict_next_race(args.model, args.data_prefix, effective_year, args.next_mode)


if __name__ == "__main__":
    main()
