def configure_fastf1_logging(debug: bool = False) -> None:
    """Keep FastF1 internals quiet unless detailed diagnostics are requested."""
    level = logging.DEBUG if debug else logging.WARNING
    for logger_name in ('fastf1', 'fastf1.api', 'fastf1.req', 'requests_cache'):
        logging.getLogger(logger_name).setLevel(level)


def resolve_data_file(prefix: str, key: str) -> Path:
    """
    Resolve a data file path using the selected prefix, with legacy fallback.
    """
    preferred = DATA_DIR / f"{prefix}_{key}.csv"
    if preferred.exists():
        return preferred

    legacy = DATA_DIR / f"f1_data_2023_{key}.csv"
    if legacy.exists():
        logger.warning(f"Using legacy data file {legacy.name}; regenerate with prefix '{prefix}' for latest data.")
        return legacy

    return preferred


def resolve_cli_year(year_arg: str, parser: argparse.ArgumentParser) -> int:
    """
    Resolve CLI year argument.

    Supports numeric years and dynamic aliases: auto/current/today.
    """
    normalized = str(year_arg).strip().lower()
    if normalized in {'auto', 'current', 'today'}:
        return pd.Timestamp.now().year
    if normalized.isdigit():
        return int(normalized)

    parser.error(f"Invalid value for --year: '{year_arg}'. Use a 4-digit year or 'auto'.")
    return pd.Timestamp.now().year


def get_current_standings(
    year: int,
    data_prefix: str = DEFAULT_DATA_PREFIX
) -> pd.DataFrame:
    """
    Get live driver and constructor standings as of today.
    Calculated from completed race results in the selected season.
    """
    from .data_collector import get_event_schedule, get_race_results

    schedule = get_event_schedule(year)
    if schedule.empty:
        logger.warning(f"No race schedule available for {year}")
        return pd.DataFrame()

    completed_rounds = schedule[schedule['EventDate'] < pd.Timestamp.now()]['RoundNumber'].tolist()

    if not completed_rounds:
        logger.warning(f"No completed races in {year}")
        return pd.DataFrame()

    # Prefer the locally collected dataset to avoid reloading every session.
    races_path = resolve_data_file(data_prefix, "races")
    all_races = pd.DataFrame()
    if races_path.exists():
        local_races = pd.read_csv(races_path)
        local_races['Year'] = pd.to_numeric(local_races['Year'], errors='coerce')
        local_races['Round'] = pd.to_numeric(local_races['Round'], errors='coerce')
        all_races = local_races[
            (local_races['Year'] == year) &
            (local_races['Round'].isin(pd.to_numeric(completed_rounds)))
        ].copy()

    if all_races.empty:
        logger.warning(
            "No local race data found for %s in %s; fetching completed results.",
            year,
            races_path.name
        )
        races = []
        for round_num in completed_rounds:
            result = get_race_results(year, round_num)
            if not result.empty:
                races.append(result)

        if not races:
            return pd.DataFrame()
        all_races = pd.concat(races, ignore_index=True)

    # Use official points from race results when available.
    if 'Points' in all_races.columns:
        all_races['RacePoints'] = pd.to_numeric(all_races['Points'], errors='coerce').fillna(0)
    else:
        points_map = {
            1: 25, 2: 18, 3: 15, 4: 12, 5: 10,
            6: 8, 7: 6, 8: 4, 9: 2, 10: 1
        }
        all_races['Position'] = pd.to_numeric(all_races['Position'], errors='coerce')
        all_races['RacePoints'] = all_races['Position'].map(points_map).fillna(0)

    # Driver standings (as of latest completed race)
    driver_points = all_races.groupby('Abbreviation', as_index=False)['RacePoints'].sum()
    driver_points = driver_points.rename(columns={
        'Abbreviation': 'Driver',
        'RacePoints': 'DriverPointsBefore'
    })
    driver_points['DriverChampionshipPosition'] = driver_points['DriverPointsBefore'].rank(
        ascending=False,
        method='min'
    )

    # Team mapping and constructor standings
    driver_team = all_races[['Abbreviation', 'TeamName']].dropna().drop_duplicates(subset=['Abbreviation'], keep='last')
    driver_team = driver_team.rename(columns={'Abbreviation': 'Driver'})
    driver_points = driver_points.merge(driver_team, on='Driver', how='left')

    constructor_points = all_races.groupby('TeamName', as_index=False)['RacePoints'].sum()
    constructor_points = constructor_points.rename(columns={'RacePoints': 'ConstructorPointsBefore'})
    constructor_points['ConstructorChampionshipPosition'] = constructor_points['ConstructorPointsBefore'].rank(
        ascending=False,
        method='min'
    )

    standings = driver_points.merge(
        constructor_points[['TeamName', 'ConstructorPointsBefore', 'ConstructorChampionshipPosition']],
        on='TeamName',
        how='left'
    )
    standings['Year'] = year
    standings['Round'] = max(completed_rounds)

    return standings.sort_values('DriverChampionshipPosition').reset_index(drop=True)


def display_current_standings(year: int, data_prefix: str = DEFAULT_DATA_PREFIX):
    """Display live championship standings based on completed races up to today."""
    standings = get_current_standings(year, data_prefix)
